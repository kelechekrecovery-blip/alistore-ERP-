import { Prisma } from '@prisma/client';

/**
 * Нарушение уникального индекса (Prisma `P2002`).
 *
 * Этот предикат был написан заново в двадцати местах, в двух несовместимых
 * формах: пятнадцать проверяли `instanceof PrismaClientKnownRequestError`, пять —
 * утиную типизацию по полю `code`. Расхождение не косметическое: от этой проверки
 * зависит, станет ли гонка двух одинаковых запросов **успешным реплеем** или
 * ошибкой пользователю, и это денежные маршруты — платежи, закупки, финансы,
 * заказы. Один маршрут восстанавливался после гонки, соседний нет, и заметить
 * это можно было только под нагрузкой.
 *
 * Здесь принимаются **обе** формы, поэтому переход на общий предикат ничего не
 * сужает:
 * - `instanceof` — точная проверка, но она ломается, если ошибка пересекла
 *   границу модульного realm (две копии `@prisma/client` в дереве): прототип
 *   теряется, `code` остаётся;
 * - утиная типизация ловит и такой случай, но сама по себе пропустила бы любой
 *   объект с этим полем — поэтому значение сверяется строго со строкой `P2002`.
 */
export function isUniqueConstraintViolation(error: unknown): boolean {
  if (error instanceof Prisma.PrismaClientKnownRequestError) return error.code === 'P2002';
  return typeof error === 'object'
    && error !== null
    && 'code' in error
    && (error as { code: unknown }).code === 'P2002';
}
