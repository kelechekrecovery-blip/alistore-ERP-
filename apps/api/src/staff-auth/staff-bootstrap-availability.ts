export type BootstrapEnvReader = (name: string) => string | undefined;

/**
 * Доступно ли одноразовое создание первого владельца.
 *
 * Маршрут `POST /staff-auth/bootstrap` создаёт учётку с ролью `owner` без
 * какой-либо авторизации. Единственное, что его закрывает — непустая таблица
 * персонала. Это защита состоянием данных, и она переживает не всё: неполное
 * восстановление из дампа, ошибка миграции, случайный `deleteMany` — и
 * публичный маршрут снова раздаёт права владельца тому, кто успел первым.
 *
 * Вторая защёлка независима от данных: в production маршрута нет вовсе.
 * Открывается только явным `STAFF_BOOTSTRAP_ENABLED=true` — чтобы честное
 * первое развёртывание осталось возможным, но было осознанным действием
 * владельца, а не состоянием по умолчанию.
 *
 * Сравнение строгое: `'1'` и `'yes'` не считаются согласием. Флаг, который
 * включается «чем-нибудь похожим на да», рано или поздно включится сам.
 */
export function isStaffBootstrapAvailable(env: BootstrapEnvReader): boolean {
  if (env('NODE_ENV') !== 'production') return true;
  return env('STAFF_BOOTSTRAP_ENABLED')?.trim().toLowerCase() === 'true';
}
